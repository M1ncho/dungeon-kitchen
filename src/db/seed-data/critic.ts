export type CriticTextSeed = { code: string; kind: string; item: string; tier: string; tag: string; text: string };

/** code 는 "kind.item.tier.tag.n" (n 은 같은 묶음 안의 순번). 문장을 고치면 같은 code 가 갱신된다. */
export const CRITIC_TEXTS: CriticTextSeed[] = (() => {
  const counter = new Map<string, number>();
  return [...INTRO, ...PRAISE, ...COMPLAINT, ...STARS].map(([kind, item, tier, tag, text]) => {
    const key = [kind, item || "-", tier || "-", tag || "-"].join(".");
    const n = (counter.get(key) ?? 0) + 1;
    counter.set(key, n);
    return { code: `${key}.${n}`, kind, item, tier, tag, text };
  });
})();
